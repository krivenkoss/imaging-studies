"""API-REGISTRY generator (../REFERENCE.md#api-registry; OPEN-BACKLOG Q-REGISTRY-GEN).

Reads src/imstudies/core/*.py with `ast` - the package is never imported - and prints Markdown:
a header with the UTC date and the core commit, then per module its public functions with
signatures, public classes (NamedTuple fields, __init__ signature) and REFUSAL_REASONS.
Names starting with "_" are skipped. Usage: python tools/api_registry.py [--commit HASH]
"""

import argparse
import ast
import copy
import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def read_commit(root):
    """HEAD commit read from the files of .git (no git call): loose ref, packed ref or detached."""
    git = Path(root) / ".git"
    head = (git / "HEAD").read_text(encoding="ascii").strip()
    if not head.startswith("ref: "):
        return head
    ref = head[len("ref: "):]
    if (git / ref).is_file():
        return (git / ref).read_text(encoding="ascii").strip()
    packed = git / "packed-refs"
    for line in packed.read_text(encoding="ascii").splitlines() if packed.is_file() else []:
        if line.endswith(" " + ref):
            return line.split()[0]
    raise SystemExit(f"no commit for {ref} under {git}; pass --commit")


def _signature(name, fn, drop_self=False):
    args = copy.copy(fn.args)
    if drop_self:
        args.args = args.args[1:]
    return f"{name}({ast.unparse(args)})" + (f" -> {ast.unparse(fn.returns)}" if fn.returns else "")


def module_lines(path):
    """Markdown list lines of the public names of one module, in source order."""
    lines = []
    for node in ast.parse(Path(path).read_text(encoding="utf-8")).body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            lines.append(f"- `{_signature(node.name, node)}`")
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            bases = [ast.unparse(b) for b in node.bases]
            parts = []
            if any(b.split(".")[-1] == "NamedTuple" for b in bases):
                parts.append("fields " + ", ".join(f"`{ast.unparse(s)}`" for s in node.body
                                                   if isinstance(s, ast.AnnAssign)))
            for s in node.body:
                if isinstance(s, ast.FunctionDef) and s.name == "__init__":
                    parts.append(f"`{_signature(node.name, s, drop_self=True)}`")
            head = f"- class `{node.name}({', '.join(bases)})`" if bases else f"- class `{node.name}`"
            lines.append(head + (": " + "; ".join(parts) if parts else ""))
        elif isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "REFUSAL_REASONS" for t in node.targets):
            lines.append("- `REFUSAL_REASONS`: " + ", ".join(f"`{r}`" for r in ast.literal_eval(node.value)))
    return lines


def registry(root=ROOT, commit=None, now=None):
    root = Path(root)
    now = now or datetime.datetime.now(datetime.timezone.utc)
    out = [f"Snapshot {now:%Y-%m-%d %H:%M} UTC, core commit `{commit or read_commit(root)}`; "
           f"generated by `tools/api_registry.py` from `src/imstudies/core/*.py`."]
    for path in sorted((root / "src" / "imstudies" / "core").glob("*.py")):
        lines = module_lines(path)
        if lines:
            name = ".".join(path.relative_to(root / "src").with_suffix("").parts).removesuffix(".__init__")
            out += ["", f"### `{name}`", "", *lines]
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--commit", help="commit to print instead of the one read from .git/HEAD")
    print(registry(commit=parser.parse_args().commit))
